using System.Collections;
using UnityEngine;
using UnityEngine.InputSystem;
using UnityEngine.UI;
using UnityEngine.Video;

namespace Kneel.UI
{
    // New Game's opening: the prologue film, a fade to black, a card ("YOU HAVE AWAKENED"), then L1, where Kael wakes in the water
    // beside the broken relic (L1WakeUp fades the level in from black). The film ends on him lying there, so the wake-up
    // picks up its last shot.
    //
    // The film can be skipped: the first press of Esc, Enter, Space or a gamepad's Start/South shows "Press again to
    // skip", and a second press within skipHintTime cuts to the fade. The title card always plays. L1 starts loading
    // under the fade (never during the film, so loading can't stutter it) and activates once the card has faded out.
    // The scene is generated by Kneel/UI/Build Intro Scene (Editor/UI/IntroSceneBuilder.cs); change that and rerun it.
    public class IntroSequence : MonoBehaviour
    {
        [SerializeField] private string nextScene = "L1_BrokenLine_Playable";

        [Header("Film")]
        [SerializeField] private VideoPlayer video;
        [SerializeField] private AudioSource videoAudio;
        // The film is drawn into a render texture made at the clip's size and shown here.
        [SerializeField] private RawImage screen;
        [SerializeField] private float filmVolume = 1f;
        // Seconds before the film's end where the fade to black starts (it fades over filmFadeOut).
        [SerializeField] private float filmFadeOut = 1.5f;

        [Header("Black, title card, skip hint")]
        [SerializeField] private CanvasGroup black;
        [SerializeField] private CanvasGroup card;
        [SerializeField] private CanvasGroup skipHint;
        [SerializeField] private float blackBeforeCard = 0.8f;
        [SerializeField] private float cardFadeIn = 1.8f;
        [SerializeField] private float cardHold = 2.5f;
        [SerializeField] private float cardFadeOut = 1.5f;
        [SerializeField] private float blackAfterCard = 0.6f;
        [SerializeField] private float skipHintTime = 2.5f;

        // For tests: how far the sequence has got.
        public string Phase { get; private set; } = "Starting";

        private RenderTexture film;
        private bool skipRequested;
        private float hintShownAt = -100f;

        private IEnumerator Start()
        {
            Time.timeScale = 1f;
            Cursor.visible = false;
            black.alpha = 1f;
            card.alpha = 0f;
            skipHint.alpha = 0f;

            Phase = "Preparing";
            if (video.clip != null && screen != null)
            {
                film = new RenderTexture((int)video.clip.width, (int)video.clip.height, 0) { name = "IntroFilm" };
                video.targetTexture = film;
                screen.texture = film;
            }

            video.Prepare();
            float waited = 0f;
            while (video.isPrepared == false && waited < 10f)
            {
                waited += Time.unscaledDeltaTime;
                yield return null;
            }

            if (video.isPrepared)
            {
                if (videoAudio != null)
                {
                    videoAudio.volume = filmVolume;
                }

                // The film ends on its own end event, not on isPlaying: just after Play() the player can still report
                // not playing, and reading that as the end skipped the whole film.
                bool ended = false;
                video.loopPointReached += _ => ended = true;
                video.Play();
                Phase = "Film";
                float started = 0f;
                while (video.isPlaying == false && ended == false && started < 3f)
                {
                    started += Time.unscaledDeltaTime;
                    yield return null;
                }

                // The film starts on black: lift the cover as soon as frames arrive.
                while (video.frame < 1 && ended == false && video.isPlaying)
                {
                    yield return null;
                }

                black.alpha = 0f;
                double length = video.length;
                while (skipRequested == false && ended == false && video.isPlaying && video.time < length - filmFadeOut)
                {
                    yield return null;
                }
            }
            else
            {
                Debug.LogWarning("Intro: the film didn't prepare in time; going straight to the title card.", this);
            }

            Phase = "FadeOut";
            skipHint.alpha = 0f;
            float fadeFrom = videoAudio != null ? videoAudio.volume : 0f;
            yield return Fade(black, 1f, filmFadeOut, t =>
            {
                if (videoAudio != null)
                {
                    videoAudio.volume = Mathf.Lerp(fadeFrom, 0f, t);
                }
            });
            video.Stop();

            // L1 loads under the black and the card.
            AsyncOperation next = SceneLoader.Preload(nextScene);
            if (next == null)
            {
                Debug.LogError($"Intro can't load '{nextScene}': add it to the Build Profiles scene list.", this);
            }

            yield return Wait(blackBeforeCard);
            Phase = "Card";
            yield return Fade(card, 1f, cardFadeIn, null);
            yield return Wait(cardHold);
            yield return Fade(card, 0f, cardFadeOut, null);
            yield return Wait(blackAfterCard);

            Phase = "Loading";
            while (next != null && next.progress < 0.9f)
            {
                yield return null;
            }

            // The switch runs on the loader, which outlives this scene: activating L1 destroys this object, and a
            // coroutine of its own would stop before lifting the black (it did: the level stayed black).
            SceneLoader loader = SceneLoader.Instance;
            loader.SetBlack(1f);
            loader.StartCoroutine(ActivateAndReveal(loader, next));
        }

        // Activates the loaded level under the loader's black, then lifts it. The wake-up's own fade from black is
        // under it, so the reveal is the wake-up's.
        private static IEnumerator ActivateAndReveal(SceneLoader loader, AsyncOperation next)
        {
            if (next != null)
            {
                next.allowSceneActivation = true;
                while (next.isDone == false)
                {
                    yield return null;
                }
            }

            yield return loader.FadeTo(0f, 0.4f);
        }

        private void Update()
        {
            if (Phase != "Film" || skipRequested)
            {
                return;
            }

            bool pressed = (Keyboard.current != null && (Keyboard.current.escapeKey.wasPressedThisFrame || Keyboard.current.enterKey.wasPressedThisFrame || Keyboard.current.spaceKey.wasPressedThisFrame))
                || (Gamepad.current != null && (Gamepad.current.startButton.wasPressedThisFrame || Gamepad.current.buttonSouth.wasPressedThisFrame));
            if (pressed)
            {
                if (Time.unscaledTime - hintShownAt <= skipHintTime)
                {
                    skipRequested = true;
                }
                else
                {
                    hintShownAt = Time.unscaledTime;
                }
            }

            float since = Time.unscaledTime - hintShownAt;
            skipHint.alpha = since <= skipHintTime ? Mathf.Clamp01(Mathf.Min(since / 0.2f, (skipHintTime - since) / 0.4f)) * 0.7f : 0f;
        }

        private void OnDestroy()
        {
            if (film != null)
            {
                film.Release();
                Destroy(film);
            }
        }

        // For tests: as if the skip were pressed twice.
        public void Skip() => skipRequested = true;

        private static IEnumerator Fade(CanvasGroup group, float to, float duration, System.Action<float> alongside)
        {
            float from = group.alpha;
            for (float t = 0f; t < duration; t += Time.unscaledDeltaTime)
            {
                float k = Mathf.SmoothStep(0f, 1f, t / duration);
                group.alpha = Mathf.Lerp(from, to, k);
                alongside?.Invoke(k);
                yield return null;
            }

            group.alpha = to;
            alongside?.Invoke(1f);
        }

        private static IEnumerator Wait(float seconds)
        {
            for (float t = 0f; t < seconds; t += Time.unscaledDeltaTime)
            {
                yield return null;
            }
        }
    }
}
